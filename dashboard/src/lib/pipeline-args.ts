/**
 * Pure argument builder for the Python pipeline.  Kept separate from the
 * process spawner so the prepare-vs-submit contract can be regression-tested:
 *
 * - dashboard "Prepare"  → apply <job> --limit 1        (never --yes)
 * - dashboard "Submit"   → apply <job> --submit --limit 1
 * - bulk                 → apply --limit N              (never --yes)
 */
export type StartOptions = { jobId?: string; submit?: boolean };

export function buildPipelineArgs(stage: string, limit: number, opts?: StartOptions): string[] {
  const args = ["-m", "applyforme", stage];
  if (stage === "apply") {
    if (opts?.jobId) args.push(opts.jobId);
    // Explicit one-application authorization only.  --yes is deliberately
    // never generated by the dashboard.
    if (opts?.submit) args.push("--submit");
    args.push("--limit", String(limit));
  } else if (stage === "tailor" && opts?.jobId) {
    args.push(opts.jobId, "--limit", "1");
  } else if (stage === "cleanup") {
    args.push("--days", process.env.JOB_RETENTION_DAYS || "10");
  } else if (stage === "inbox") {
    args.push("--days", "14");
  } else {
    args.push("--limit", String(limit));
  }
  return args;
}
